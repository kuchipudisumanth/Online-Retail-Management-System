CREATE OR REPLACE PACKAGE XX_TEAM1_ORMS_PKG AS
 
   PROCEDURE ORDERS_REPORT(errbuf OUT VARCHAR2, retcode OUT VARCHAR2);
 
   PROCEDURE MANAGER_ORDERS_REPORT(
      errbuf OUT VARCHAR2,
      retcode OUT VARCHAR2,
      p_manager_id IN NUMBER
   );
 
   PROCEDURE SALES_REPORT(errbuf OUT VARCHAR2, retcode OUT VARCHAR2);
 
END XX_TEAM1_ORMS_PKG;
/
 
 
 
 
 
CREATE OR REPLACE PACKAGE BODY XX_TEAM1_ORMS_PKG AS
 
------------------------------------------------------------------
-- 1. Orders Report
------------------------------------------------------------------
PROCEDURE ORDERS_REPORT(errbuf OUT VARCHAR2, retcode OUT VARCHAR2)
IS
BEGIN
   FOR rec IN (
      SELECT o.order_id,
             c.customer_name,
             o.order_date,
             o.total_amount,
             o.order_status
      FROM xx_team1_orms_orders o,
           xx_team1_orms_customers c
      WHERE o.customer_id = c.customer_id
   )
   LOOP
      fnd_file.put_line(fnd_file.output,
         rec.order_id || ' | ' ||
         rec.customer_name || ' | ' ||
         rec.order_date || ' | ' ||
         rec.total_amount || ' | ' ||
         rec.order_status);
   END LOOP;
 
EXCEPTION
   WHEN OTHERS THEN
      errbuf := SQLERRM;
      retcode := '2';
END;
 
------------------------------------------------------------------
-- 2. Manager Orders Report (IMPORTANT requirement)
------------------------------------------------------------------
PROCEDURE MANAGER_ORDERS_REPORT(
   errbuf OUT VARCHAR2,
   retcode OUT VARCHAR2,
   p_manager_id IN NUMBER
)
IS
BEGIN
   FOR rec IN (
      SELECT o.order_id,
             o.order_date,
             o.total_amount,
             o.order_status
      FROM xx_team1_orms_orders o
      WHERE o.manager_id = p_manager_id
   )
   LOOP
      fnd_file.put_line(fnd_file.output,
         rec.order_id || ' | ' ||
         rec.order_date || ' | ' ||
         rec.total_amount || ' | ' ||
         rec.order_status);
   END LOOP;
 
EXCEPTION
   WHEN OTHERS THEN
      errbuf := SQLERRM;
      retcode := '2';
END;
 
------------------------------------------------------------------
-- 3. Sales Report
------------------------------------------------------------------
PROCEDURE SALES_REPORT(errbuf OUT VARCHAR2, retcode OUT VARCHAR2)
IS
BEGIN
   FOR rec IN (
      SELECT p.product_name,
             SUM(ol.quantity) total_qty,
             SUM(ol.line_amount) total_sales
      FROM xx_team1_orms_order_lines ol,
           xx_team1_orms_products p
      WHERE ol.product_id = p.product_id
      GROUP BY p.product_name
   )
   LOOP
      fnd_file.put_line(fnd_file.output,
         rec.product_name || ' | ' ||
         rec.total_qty || ' | ' ||
         rec.total_sales);
   END LOOP;
 
EXCEPTION
   WHEN OTHERS THEN
      errbuf := SQLERRM;
      retcode := '2';
END;
 
END XX_TEAM1_ORMS_PKG;
